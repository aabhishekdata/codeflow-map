#!/usr/bin/env python3
"""Module map and module deep-dive analysis for codeflow-map (read-only, static).

Finds the modules (parts) of a code base, how they depend on each other, and - for every module -
what is inside it: files, classes, functions, who calls what, the control flow of key functions,
the data model, and draft data-flow / sequence pictures. Writes everything as flow-map views that
build_flowmap.py turns into the interactive HTML.

Usage:
    python analyze_modules.py <repo> [--out .codeflow/modules.json]
    python analyze_modules.py <repo> --select billing,claims          # extra depth for the chosen modules
    python analyze_modules.py <repo> --cfg backend/app/crud.py:create_user   # add one function's control flow
    python analyze_modules.py <repo> --diff main                       # what changed since a branch / commit
    python analyze_modules.py <repo> --module-depth 3 | --modules-config modules.json
    python analyze_modules.py <repo> --report .codeflow/module-report.md

Python is analysed with the standard-library `ast`. JavaScript / TypeScript is analysed with Node
(scripts/js_facts.cjs + the vendored Babel parser); without Node, JS/TS falls back to import scanning only.
Never executes project code, never reads .env files, never prints secret values.
Standard library only (Python 3.8+).
"""

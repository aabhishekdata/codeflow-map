def slug(s):
    s = re.sub(r"[^A-Za-z0-9]+", "-", str(s)).strip("-").lower()
    return s or "root"


SECRET_ASSIGN = re.compile(r"(?i)\b([\w.]*(?:password|passwd|pwd|secret|api[_-]?key|token|private[_-]?key|credential|conn(?:ection)?[_-]?str(?:ing)?)[\w]*['\"]?\s*(?::|=|==|\()\s*)(f|r|b|u)?(['\"`])((?:(?!\3).){3,})\3")
SECRET_SHAPES = re.compile(r"(AKIA[0-9A-Z]{16}|\bgh[pousr]_[A-Za-z0-9]{20,}|\bsk-[A-Za-z0-9_-]{16,}|-----BEGIN [A-Z ]*PRIVATE KEY-----|"
                           r"(?:jdbc|postgres(?:ql)?|mysql|mongodb(?:\+srv)?|redis|amqp)://[^\s'\"]*:[^\s'\"@]+@)")


def redact(s):
    """Hide literal values assigned to secret-looking names (password = "x" -> password = "•••") and known key shapes."""
    s = SECRET_ASSIGN.sub(lambda m: m.group(1) + (m.group(2) or "") + m.group(3) + "•••" + m.group(3), s)
    return SECRET_SHAPES.sub("•••", s)


SECRET_WORD = re.compile(r"(?i)\b((?:[\w.-]*?)(?:password|passwd|pwd|passphrase|secret|api[_-]?key|access[_-]?key|token|"
                         r"private[_-]?key|credential|conn(?:ection)?[_-]?str(?:ing)?|bearer|auth[_-]?key)[\w.-]*)"
                         r"(\s*(?:[:=]+|\bis\b)\s*)([^\s,;)]+)")
LONG_TOKEN = re.compile(r"\b(?=[A-Za-z0-9_\-]*\d)(?=[A-Za-z0-9_\-]*[A-Za-z])[A-Za-z0-9_\-]{24,}\b|\b(?:sk|pk|rk)_(?:live|test)_[A-Za-z0-9]{8,}")


def redact_prose(s):
    """redact() plus what comments and docs add: unquoted values after secret-looking words
    ("password is hunter2", "api_key=abc") and long random-looking tokens."""
    s = redact(str(s or ""))
    s = SECRET_WORD.sub(lambda m: m.group(1) + m.group(2) + ("•••" if m.group(3) != "•••" else m.group(3)), s)
    return LONG_TOKEN.sub("•••", s)


def oneline(s, n):
    s = re.sub(r"\s+", " ", str(s or "")).strip()
    return s if len(s) <= n else s[:n - 1] + "…"



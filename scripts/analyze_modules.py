def strip_jsonc(text):
    out, i, n, in_str, q = [], 0, len(text), False, ""
    while i < n:
        c = text[i]
        if in_str:
            out.append(c)
            if c == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 2
                continue
            if c == q:
                in_str = False
        elif c in "\"'":
            in_str, q = True, c
            out.append(c)
        elif text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
            continue
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            i = n if j < 0 else j + 2
            continue
        else:
            out.append(c)
        i += 1
    return re.sub(r",(\s*[}\]])", r"\1", "".join(out))


class Resolver:
    def __init__(self, root, files):
        self.root = root
        self.files = set(files)
        self.py_mod = {}
        for r in files:
            if r.endswith(".py"):
                mod = r[:-3].replace("/", ".")
                if mod.endswith(".__init__"):
                    mod = mod[:-9]
                self.py_mod[mod] = r
        self.py_suffix = defaultdict(list)
        for mod, r in self.py_mod.items():
            parts = mod.split(".")
            for i in range(len(parts)):
                self.py_suffix[".".join(parts[i:])].append(r)
        self.tsconfigs = {}
        for dp, dns, fns in os.walk(root):
            dns[:] = [d for d in dns if d not in SR.SKIP_DIRS and not d.startswith(".")]
            for fn in fns:
                if re.match(r"^(tsconfig|jsconfig)(\.[\w-]+)?\.json$", fn):
                    try:
                        cfg = json.loads(strip_jsonc((Path(dp) / fn).read_text(encoding="utf-8", errors="ignore")))
                    except ValueError:
                        continue
                    co = cfg.get("compilerOptions") or {}
                    if co.get("paths") or co.get("baseUrl"):
                        d = SR.rel(Path(dp), root) if Path(dp) != root else ""
                        base = os.path.normpath(os.path.join(d, co.get("baseUrl") or ".")).replace(os.sep, "/")
                        self.tsconfigs.setdefault(d, []).append((base if base != "." else "", co.get("paths") or {}))

    # ---------------- Python
    def py_module_file(self, dotted):
        if not dotted:
            return None
        if dotted in self.py_mod:
            return self.py_mod[dotted]
        hits = self.py_suffix.get(dotted)
        if hits and len(hits) == 1:
            return hits[0]
        if hits:
            return sorted(hits, key=len)[0]
        return None

    def py_import(self, rel, imp):
        """Returns list of (local_name, target_file, symbol_or_None) and list of target files."""
        pkg = rel.rsplit("/", 1)[0].replace("/", ".") if "/" in rel else ""
        if rel.endswith("/__init__.py"):
            pkg = rel[:-12].replace("/", ".")
        mod = imp["module"]
        if imp["level"]:
            base = pkg.split(".") if pkg else []
            base = base[:len(base) - (imp["level"] - 1)] if imp["level"] > 1 else base
            mod = ".".join([p for p in base + ([mod] if mod else []) if p])
        out = []
        if not imp["names"]:  # import a.b.c [as x]
            f = None
            parts = mod.split(".")
            for i in range(len(parts), 0, -1):
                f = self.py_module_file(".".join(parts[:i]))
                if f:
                    break
            if f:
                out.append((imp["alias"], f, None))
            return out
        mf = self.py_module_file(mod)
        for name, local in imp["names"]:
            if name == "*":
                if mf:
                    out.append(("*", mf, "*"))
                continue
            sub = self.py_module_file(mod + "." + name) if mod else self.py_module_file(name)
            if sub:
                out.append((local, sub, None))
            elif mf:
                out.append((local, mf, name))
        return out

    # ---------------- JS / TS
    def js_candidates(self, base):
        base = base.replace(os.sep, "/")
        stem = re.sub(r"\.(js|jsx|mjs|cjs)$", "", base)
        exts = ["", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".mts", ".vue", ".svelte", "/index.ts", "/index.tsx", "/index.js", "/index.jsx"]
        for b in (base, stem):
            for e in exts:
                c = b + e
                if c in self.files:
                    return c
        return None

    def js_import(self, rel, spec):
        d = rel.rsplit("/", 1)[0] if "/" in rel else ""
        if spec.startswith("."):
            return self.js_candidates(os.path.normpath(os.path.join(d, spec)))
        # tsconfig paths from the nearest config up the tree
        parts = d.split("/") if d else []
        for i in range(len(parts), -1, -1):
            key = "/".join(parts[:i])
            for base, paths in self.tsconfigs.get(key, []):
                for pat, targets in paths.items():
                    if pat.endswith("*") and spec.startswith(pat[:-1]):
                        rest = spec[len(pat) - 1:]
                    elif pat == spec:
                        rest = ""
                    else:
                        continue
                    for t in targets:
                        cand = os.path.normpath(os.path.join(base, t.replace("*", rest)))
                        hit = self.js_candidates(cand)
                        if hit:
                            return hit
                hit = self.js_candidates(os.path.normpath(os.path.join(base, spec)))  # baseUrl-relative
                if hit:
                    return hit
        if spec.startswith("@/") or spec.startswith("~/"):
            src = rel[:rel.index("src/") + 4] if "src/" in rel else "src/"
            return self.js_candidates(os.path.normpath(src + spec[2:]))
        return None



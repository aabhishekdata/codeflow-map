def collect_files(root, sub, include_tests):
    SR.INCLUDE_TESTS = True
    found = list(SR.walk(root, sub))
    SR.INCLUDE_TESTS = False
    code, tests = [], []
    for p in found:
        ext = p.suffix.lower()
        if ext not in JS_EXT and ext not in PY_EXT and ext not in (".sql", ".prisma"):
            continue
        r = SR.rel(p, root)
        parts = r.split("/")
        is_test = bool(SR.TEST_FILE.search(p.name)) or any(x.lower() in SR.TEST_DIRS for x in parts[:-1])
        (tests if is_test else code).append(r)
    if include_tests:
        code += tests
    return sorted(code), sorted(tests)


def is_generated(rel, text):
    if GENERATED.search(rel):
        return True
    head = "\n".join((text or "").splitlines()[:6])
    return bool(GENERATED_HEAD.search(head))



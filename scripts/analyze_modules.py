    def datamodel_view(self, M):
        A, s = self.A, self.s(M)
        mine = list(M["tables"])
        if not mine:
            return None
        all_tables = {}
        for c in A.cls_index.values():
            if A.is_table(c):
                all_tables[A.table_name(c).lower()] = c
                all_tables[c["name"].lower()] = c
        for MM in A.modules.values():
            for t in MM["tables"]:
                if t.get("sql"):
                    all_tables[t["name"].lower()] = t
                    all_tables[t["name"].split(".")[-1].lower()] = t
        ents, rels, ext = [], [], {}

        def attrs_of(t):
            out = []
            if t.get("sql"):
                for c in t["sql"]["columns"]:
                    out.append({"name": c["name"], "type": c.get("type", ""), "key": " ".join(k for k, v in (("PK", c.get("pk")), ("FK", c.get("fk")), ("UK", c.get("unique"))) if v),
                                "sensitive": bool(SENSITIVE_NAME.search(c["name"]))})
                return out
            for p in t.get("props", []):
                if p.get("relationship") or p["name"].startswith("_") or p["name"] in ("model_config", "Config", "Meta") \
                        or (p.get("call") or "").endswith("Manager") or (p["name"].isupper() and len(p["name"]) > 2):
                    continue
                typ = p.get("coltype") or re.sub(r"\s*\|\s*None", "", p.get("type") or "").split("[")[-1].strip("] '\"") or "field"
                out.append({"name": p["name"], "type": typ.split(".")[-1], "key": " ".join(k for k, v in (("PK", p.get("pk")), ("FK", p.get("fk")), ("UK", p.get("unique"))) if v),
                            "sensitive": bool(SENSITIVE_NAME.search(p["name"]))})
            return out

        def ent_id(t):
            return "t-" + slug(t.get("name"))

        def fk_target(fk):
            k = fk.split(".")[0].lower() if "." in fk else fk.lower()
            return all_tables.get(k)

        def add_bases(t):   # SQLModel / pydantic: table classes inherit fields from base classes
            if t.get("sql"):
                return t
            props = list(t.get("props", []))
            for b in t.get("bases", []):
                bc = next((c for c in A.cls_index.values() if c["name"] == (b or "").split(".")[-1]), None)
                if bc and not A.is_table(bc):
                    names = {p["name"] for p in props}
                    props += [p for p in bc.get("props", []) if p["name"] not in names]
            return dict(t, props=props)
        for t in mine:
            t = add_bases(t)
            attrs = attrs_of(t)
            ents.append({"id": ent_id(t), "key": "t:" + A.table_name(t).lower(), "label": A.table_name(t), "technical": "%s (%s:%d)" % (t["name"], t["file"], t["line"]), "attributes": attrs,
                         "files": [self.ev(t["file"], t["line"])], "confidence": "verified",
                         "description": "Table %s, defined in %s. %d field%s%s." % (A.table_name(t), t["file"], len(attrs), "" if len(attrs) == 1 else "s",
                                                                                 "; holds personal-looking fields: " + ", ".join(a["name"] for a in attrs if a["sensitive"]) if any(a["sensitive"] for a in attrs) else ""),
                         "sensitive_data": [a["name"] for a in attrs if a["sensitive"]]})
            for p in (t["sql"]["columns"] if t.get("sql") else t.get("props", [])):
                if p.get("fk"):
                    tgt = fk_target(p["fk"])
                    if tgt:
                        if tgt not in mine:
                            ext[ent_id(tgt)] = tgt
                        rels.append({"from": ent_id(tgt), "to": ent_id(t), "card_from": "one", "card_to": "many", "label": p["name"],
                                     "technical": "%s.%s → %s" % (A.table_name(t), p["name"], p["fk"])})
        known = {e["id"] for e in ents}
        for eid, t in ext.items():
            if eid in known:
                continue
            ents.append({"id": eid, "label": A.table_name(t), "technical": "%s (%s)" % (t["name"], t["file"]), "attributes": [],
                         "files": [self.ev(t["file"], t["line"])], "description": "Table defined in another part; shown because tables here point to it."})
        seen, uniq = set(), []
        for r in rels:
            k = (r["from"], r["to"], r["label"])
            if k not in seen:
                seen.add(k)
                uniq.append(r)
        return {"id": "mod-%s-datamodel" % s, "title": "Data model", "kind": "detail", "module": M["id"], "facet": "datamodel", "type": "er",
                "entities": ents, "relations": uniq,
                "summary": "The database tables defined in %s, their fields and how they link. Fields marked 'sensitive' look like personal data." % M["label"],
                "technical_summary": "Entity-relationship diagram from ORM models / CREATE TABLE statements; links come from foreign keys."}


_SEG_CACHE = {"src": None, "lines": None}


def _seg(src, node):
    """Fast ast.get_source_segment: the encoded lines are computed once per file (offsets are UTF-8 bytes)."""
    if node is None or getattr(node, "end_lineno", None) is None:
        return ""
    if _SEG_CACHE["src"] is not src:
        _SEG_CACHE["src"], _SEG_CACHE["lines"] = src, [ln.encode("utf-8") for ln in src.splitlines(True)]
    L = _SEG_CACHE["lines"]
    try:
        a, b = node.lineno - 1, node.end_lineno - 1
        if a == b:
            return L[a][node.col_offset:node.end_col_offset].decode("utf-8", "replace")
        parts = [L[a][node.col_offset:]] + L[a + 1:b] + [L[b][:node.end_col_offset]]
        return b"".join(parts).decode("utf-8", "replace")
    except (IndexError, TypeError):
        return ""


def _dotted(n):
    if isinstance(n, ast.Name):
        return n.id
    if isinstance(n, ast.Attribute):
        b = _dotted(n.value)
        return (b + "." if b else "") + n.attr
    if isinstance(n, ast.Call):
        b = _dotted(n.func)
        return b + "()" if b else ""
    if isinstance(n, ast.Subscript):
        return _dotted(n.value)
    return ""


def _const_str(n):
    if isinstance(n, ast.Constant) and isinstance(n.value, str):
        return n.value
    return None


def _py_complexity(fn):
    c = 1
    stack = list(ast.iter_child_nodes(fn))
    while stack:
        n = stack.pop()
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef, ast.Lambda)):
            continue
        if isinstance(n, (ast.If, ast.For, ast.AsyncFor, ast.While, ast.IfExp, ast.ExceptHandler)):
            c += 1
        elif isinstance(n, ast.BoolOp):
            c += len(n.values) - 1
        elif isinstance(n, ast.comprehension):
            c += 1 + len(n.ifs)
        elif type(n).__name__ == "match_case":
            c += 1
        stack.extend(ast.iter_child_nodes(n))
    return c


def _py_params(src, args):
    out = []
    pos = list(getattr(args, "posonlyargs", [])) + list(args.args)
    for a in pos:
        if a.arg in ("self", "cls"):
            continue
        out.append(a.arg + (": " + oneline(_seg(src, a.annotation), 30) if a.annotation is not None else ""))
    if args.vararg:
        out.append("*" + args.vararg.arg)
    for a in args.kwonlyargs:
        out.append(a.arg + (": " + oneline(_seg(src, a.annotation), 30) if a.annotation is not None else ""))
    if args.kwarg:
        out.append("**" + args.kwarg.arg)
    return out


def _py_calls(fn):
    calls, names = [], set()
    for n in ast.walk(fn):
        if isinstance(n, ast.Call):
            f = n.func
            if isinstance(f, ast.Name):
                calls.append({"name": f.id, "line": n.lineno})
            elif isinstance(f, ast.Attribute):
                calls.append({"name": f.attr, "obj": _dotted(f.value)[:60], "line": n.lineno})
        elif isinstance(n, ast.Name):
            names.add(n.id)
    return calls[:400], names


class PyCfg:
    """Structured control-flow graph of one Python function (same format as js_facts.cjs)."""
    COMPOUND = (ast.If, ast.For, ast.AsyncFor, ast.While, ast.Try, ast.With, ast.AsyncWith, ast.Return, ast.Raise,
                ast.Break, ast.Continue)
    JUMPS = (ast.Return, ast.Raise, ast.Break, ast.Continue)

    def __init__(self, src, fn, title, max_depth):
        self.src, self.fn, self.max_depth = src, fn, max_depth
        self.nodes, self.edges, self.loops, self.finals = [], [], [], []
        start = self.add("start", title, fn.lineno)
        ends = self.seq(fn.body, [(start, "")], 0)
        if ends:
            self.link(ends, self.add("end", "end", getattr(fn, "end_lineno", fn.lineno)))

    def add(self, t, label, line):
        nid = "c%d" % len(self.nodes)
        self.nodes.append({"id": nid, "t": t, "label": label, "line": line})
        return nid

    def link(self, preds, to):
        for p, l in preds:
            self.edges.append({"from": p, "to": to, "label": l or ""})

    def first(self, node, n=46):
        return oneline(_seg(self.src, node).split("\n")[0], n)

    def compound(self, s):
        if isinstance(s, ast.Try) or type(s).__name__ in ("TryStar", "Match"):
            return True
        return isinstance(s, self.COMPOUND)

    def block_label(self, buf):
        shown = []
        for s in buf[:3]:
            t = self.first(s)
            if self.compound(s) and not isinstance(s, self.JUMPS):
                t = t.rstrip(":") + ": …"
            shown.append(t)
        more = len(buf) - len(shown)
        return "\n".join(shown) + ("\n… +%d more" % more if more > 0 else "")

    def seq(self, stmts, preds, depth):
        buf = []

        def flush(preds_):
            if not buf:
                return preds_
            n = self.add("block", self.block_label(buf), buf[0].lineno)
            self.link(preds_, n)
            del buf[:]
            return [(n, "")]

        for s in stmts:
            if not preds:
                break
            if isinstance(s, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                buf.append(s)
                continue
            if isinstance(s, ast.Expr) and isinstance(getattr(s, "value", None), ast.Constant) and isinstance(s.value.value, str):
                continue  # docstring
            simple = not self.compound(s) or (depth >= self.max_depth and not isinstance(s, self.JUMPS))
            if simple:
                buf.append(s)
                continue
            preds = flush(preds)
            preds = self.stmt(s, preds, depth)
        if preds:
            preds = flush(preds)
        return preds

    def stmt(self, s, preds, depth):
        if isinstance(s, ast.If):
            c = self.add("cond", oneline(_seg(self.src, s.test), 46) + "?", s.lineno)
            self.link(preds, c)
            t = self.seq(s.body, [(c, "yes")], depth + 1)
            f = self.seq(s.orelse, [(c, "no")], depth + 1) if s.orelse else [(c, "no")]
            return t + f
        if isinstance(s, (ast.For, ast.AsyncFor, ast.While)):
            if isinstance(s, ast.While):
                head = "while " + oneline(_seg(self.src, s.test), 34)
            else:
                head = ("async for " if isinstance(s, ast.AsyncFor) else "for ") + oneline(_seg(self.src, s.target), 18) + \
                    " in " + oneline(_seg(self.src, s.iter), 26)
            l = self.add("loop", head, s.lineno)
            self.link(preds, l)
            self.loops.append({"node": l, "breaks": []})
            b = self.seq(s.body, [(l, "each" if not isinstance(s, ast.While) else "repeat")], depth + 1)
            self.link(b, l)
            lp = self.loops.pop()
            out = [(l, "done")]
            if s.orelse:
                out = self.seq(s.orelse, out, depth + 1)
            return out + lp["breaks"]
        if isinstance(s, ast.Try) or type(s).__name__ == "TryStar":
            t = self.add("try", "try", s.lineno)
            self.link(preds, t)
            if s.finalbody:
                self.finals.append([])
            out = self.seq(s.body, [(t, "")], depth + 1)
            if s.orelse:
                out = self.seq(s.orelse, out, depth + 1)
            for h in s.handlers:
                typ = oneline(_seg(self.src, h.type), 30) if h.type is not None else ""
                hn = self.add("catch", "except" + (" " + typ if typ else ""), h.lineno)
                self.edges.append({"from": t, "to": hn, "label": "error"})
                out = out + self.seq(h.body, [(hn, "")], depth + 1)
            if s.finalbody:
                exits = self.finals.pop()
                f = self.add("finally", "finally", s.finalbody[0].lineno)
                self.link(out, f)
                for x in exits:   # return / raise inside the try still run the clean-up first
                    self.edges.append({"from": x, "to": f, "label": "clean-up first"})
                out = self.seq(s.finalbody, [(f, "")], depth + 1)
            return out
        if isinstance(s, (ast.With, ast.AsyncWith)):
            w = self.add("block", self.first(s).rstrip(":"), s.lineno)
            self.link(preds, w)
            return self.seq(s.body, [(w, "")], depth + 1)
        if type(s).__name__ == "Match":
            c = self.add("cond", "match " + oneline(_seg(self.src, s.subject), 36), s.lineno)
            self.link(preds, c)
            out, wildcard = [], False
            for case in s.cases:
                pat = oneline(_seg(self.src, case.pattern), 24)
                if pat == "_" and case.guard is None:
                    wildcard = True
                out += self.seq(case.body, [(c, "case " + pat)], depth + 1)
            if not wildcard:
                out.append((c, "no match"))
            return out
        if isinstance(s, ast.Return):
            r = self.add("return", ("return " + oneline(_seg(self.src, s.value), 40)) if s.value is not None else "return", s.lineno)
            self.link(preds, r)
            if self.finals:
                self.finals[-1].append(r)
            return []
        if isinstance(s, ast.Raise):
            r = self.add("raise", "raise " + oneline(_seg(self.src, s.exc), 40) if s.exc is not None else "raise", s.lineno)
            self.link(preds, r)
            if self.finals:
                self.finals[-1].append(r)
            return []
        if isinstance(s, ast.Break):
            if self.loops:
                self.loops[-1]["breaks"].extend(preds)
            return []
        if isinstance(s, ast.Continue):
            if self.loops:
                self.link([(p, (l + ", next") if l else "next") for p, l in preds], self.loops[-1]["node"])
            return []
        return preds


def py_cfg(src, fn, title):
    g = None
    for depth in range(6, 0, -1):
        c = PyCfg(src, fn, title, depth)
        g = {"nodes": c.nodes, "edges": c.edges, "depth": depth}
        if len(c.nodes) <= MAX_CFG_NODES:
            break
    return g


def notebook_code(path):
    """Code of a notebook, cell by cell: magics blanked, %% cells and cells that do not compile on their own
    replaced by blank lines, so one bad cell does not hide the rest. Same line layout as scan_repo.read_text."""
    try:
        nb = json.loads(Path(path).read_text(encoding="utf-8-sig", errors="ignore"))
    except (OSError, ValueError):
        return ""
    out = []
    for c in nb.get("cells", []) if isinstance(nb, dict) else []:
        src = c.get("source", "")
        src = "".join(src) if isinstance(src, list) else str(src or "")
        lines = src.split("\n")
        if c.get("cell_type") != "code" or (lines and re.match(r"^\s*%%", lines[0])):
            out.append("\n".join("" for _ in lines))
        else:
            body = "\n".join("" if re.match(r"^\s*[%!]", ln) else ln for ln in lines)
            try:
                compile(body, "<cell>", "exec", ast.PyCF_ONLY_AST)
            except (SyntaxError, ValueError, RecursionError, MemoryError):
                body = "\n".join("" for _ in lines)
            out.append(body)
        out.append("")
    return "\n".join(out)


def py_facts(rel, text, want_cfg):
    src = text
    try:
        tree = ast.parse(src)
    except (SyntaxError, ValueError) as e:
        return {"error": "could not parse: %s" % (getattr(e, "msg", None) or e)}
    except (RecursionError, MemoryError):
        return {"error": "too deeply nested or too large to parse"}
    F = {"imports": [], "classes": [], "functions": [], "loc": sum(1 for l in text.split("\n") if l.strip()),
         "main": False, "all_names": [], "routers": {}}
    # router prefixes: items_router = APIRouter(prefix="/items")
    for n in tree.body:
        if isinstance(n, ast.Assign) and isinstance(n.value, ast.Call) and _dotted(n.value.func).split(".")[-1] in ("APIRouter", "Blueprint"):
            pre = next((_const_str(k.value) for k in n.value.keywords if k.arg in ("prefix", "url_prefix")), None)
            for t in n.targets:
                if isinstance(t, ast.Name):
                    F["routers"][t.id] = pre or ""
        if isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "__all__" for t in n.targets) and isinstance(n.value, (ast.List, ast.Tuple)):
            F["all_names"] = [c for c in (_const_str(x) for x in n.value.elts) if c]
        if isinstance(n, ast.If) and "__name__" in _seg(src, n.test) and "__main__" in _seg(src, n.test):
            F["main"] = True
    for n in ast.walk(tree):
        if isinstance(n, ast.Import):
            for a in n.names:
                F["imports"].append({"module": a.name, "level": 0, "names": [], "alias": a.asname or a.name.split(".")[0],
                                     "full_alias": bool(a.asname), "line": n.lineno})
        elif isinstance(n, ast.ImportFrom):
            F["imports"].append({"module": n.module or "", "level": n.level or 0,
                                 "names": [[a.name, a.asname or a.name] for a in n.names], "line": n.lineno})

    def deco_info(fn):
        decos, route, entry = [], None, None
        for d in fn.decorator_list:
            txt = oneline(_seg(src, d), 60)
            decos.append(txt)
            f = d.func if isinstance(d, ast.Call) else d
            attr = f.attr if isinstance(f, ast.Attribute) else (f.id if isinstance(f, ast.Name) else "")
            base = _dotted(f.value) if isinstance(f, ast.Attribute) else ""
            if attr in ROUTE_DECOS and isinstance(d, ast.Call) and d.args and _const_str(d.args[0]) is not None:
                meth = attr.upper()
                if attr in ("route", "api_route"):
                    mm = next((k.value for k in d.keywords if k.arg == "methods"), None)
                    meth = ",".join(_const_str(x) or "?" for x in mm.elts).upper() if isinstance(mm, (ast.List, ast.Tuple)) else "GET"
                route = {"method": meth, "path": F["routers"].get(base, "") + _const_str(d.args[0])}
            elif attr in TASK_DECOS:
                entry = attr
        return decos, route, entry

    def fn_rec(fn, qual, cls=None):
        decos, route, entry = deco_info(fn)
        calls, names = _py_calls(fn)
        params = _py_params(src, fn.args)
        rec = {"name": fn.name, "qual": qual, "kind": "method" if cls else "function", "line": fn.lineno,
               "endLine": getattr(fn, "end_lineno", fn.lineno), "params": params,
               "async": isinstance(fn, ast.AsyncFunctionDef), "complexity": _py_complexity(fn), "calls": calls,
               "names": sorted(names)[:300], "decorators": decos,
               "returns": oneline(_seg(src, fn.returns), 30) if fn.returns is not None else ""}
        rec["loc"] = max(1, rec["endLine"] - rec["line"] + 1)
        if cls:
            rec["cls"] = cls
        if route:
            rec["route"] = route
            rec["kind"] = "route"
        if entry:
            rec["entry"] = entry
        if want_cfg:
            title = ("async " if rec["async"] else "") + qual + "(" + ", ".join(p.split(":")[0] for p in params) + ")"
            rec["cfg"] = py_cfg(src, fn, title)
        F["functions"].append(rec)

    for n in tree.body:
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)):
            fn_rec(n, n.name)
        elif isinstance(n, ast.ClassDef):
            C = {"name": n.name, "line": n.lineno, "endLine": getattr(n, "end_lineno", n.lineno),
                 "bases": [_dotted(b) or oneline(_seg(src, b), 30) for b in n.bases],
                 "keywords": {k.arg: oneline(_seg(src, k.value), 20) for k in n.keywords if k.arg},
                 "decorators": [oneline(_seg(src, d), 40) for d in n.decorator_list], "methods": [], "props": [], "table": None}
            for b in n.body:
                if isinstance(b, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    deco = [oneline(_seg(src, d), 30) for d in b.decorator_list]
                    C["methods"].append({"name": b.name, "line": b.lineno, "params": _py_params(src, b.args),
                                         "returns": oneline(_seg(src, b.returns), 30) if b.returns is not None else "",
                                         "static": any(d in ("staticmethod", "classmethod") for d in deco),
                                         "access": "private" if b.name.startswith("_") and not b.name.endswith("__") else "public"})
                    fn_rec(b, n.name + "." + b.name, cls=n.name)
                elif isinstance(b, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "__tablename__" for t in b.targets):
                    C["table"] = _const_str(b.value)
                elif isinstance(b, (ast.Assign, ast.AnnAssign)):
                    tgt = b.target if isinstance(b, ast.AnnAssign) else (b.targets[0] if len(b.targets) == 1 else None)
                    if not isinstance(tgt, ast.Name) or tgt.id.startswith("__"):
                        continue
                    C["props"].append(_py_prop(src, tgt.id, b))
            F["classes"].append(C)
    return F


def _py_prop(src, name, node):
    ann = node.annotation if isinstance(node, ast.AnnAssign) else None
    val = node.value
    p = {"name": name, "type": oneline(_seg(src, ann), 40) if ann is not None else "", "line": node.lineno}
    if isinstance(val, ast.Call):
        fname = _dotted(val.func).split(".")[-1]
        p["call"] = fname
        kw = {k.arg: k.value for k in val.keywords if k.arg}
        if fname in ("Column", "mapped_column", "Field") or fname.endswith("Field") or fname in ("ForeignKey", "OneToOneField", "ManyToManyField"):
            if kw.get("primary_key") is not None and isinstance(kw["primary_key"], ast.Constant) and kw["primary_key"].value is True:
                p["pk"] = True
            fk = _const_str(kw.get("foreign_key")) if "foreign_key" in kw else None
            for a in val.args:
                if isinstance(a, ast.Call) and _dotted(a.func).split(".")[-1] == "ForeignKey" and a.args:
                    fk = _const_str(a.args[0]) or _dotted(a.args[0])
                elif fname == "Column" and not p.get("coltype"):
                    p["coltype"] = (_dotted(a) or "").split(".")[-1].replace("()", "")
            if fname in ("ForeignKey", "OneToOneField", "ManyToManyField") and val.args:
                fk = _const_str(val.args[0]) or _dotted(val.args[0])
            if fk:
                p["fk"] = fk
            if fname.endswith("Field") and fname not in ("Field",):
                p["coltype"] = fname.replace("Field", "") or "field"
            if kw.get("unique") is not None and isinstance(kw["unique"], ast.Constant) and kw["unique"].value is True:
                p["unique"] = True
        if fname in ("relationship", "Relationship"):
            p["relationship"] = True
    return p



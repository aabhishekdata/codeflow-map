def tarjan(nodes, adj):
    index, low, on, stack, out, i = {}, {}, set(), [], [], [0]
    for v0 in nodes:
        if v0 in index:
            continue
        work = [(v0, iter(sorted(adj.get(v0, ()))))]
        index[v0] = low[v0] = i[0]
        i[0] += 1
        stack.append(v0)
        on.add(v0)
        while work:
            v, it = work[-1]
            nxt = next(it, None)
            if nxt is not None:
                if nxt not in index:
                    index[nxt] = low[nxt] = i[0]
                    i[0] += 1
                    stack.append(nxt)
                    on.add(nxt)
                    work.append((nxt, iter(sorted(adj.get(nxt, ())))))
                elif nxt in on:
                    low[v] = min(low[v], index[nxt])
                continue
            work.pop()
            if work:
                low[work[-1][0]] = min(low[work[-1][0]], low[v])
            if low[v] == index[v]:
                comp = []
                while True:
                    w = stack.pop()
                    on.discard(w)
                    comp.append(w)
                    if w == v:
                        break
                if len(comp) > 1:
                    out.append(sorted(comp))
    return out


def parse_sql_tables(text):
    """CREATE TABLE name ( col type ..., PRIMARY KEY(...), FOREIGN KEY (c) REFERENCES t(c) )"""
    out = []
    for m in re.finditer(r"\bCREATE\s+(?:OR\s+REPLACE\s+)?(?:TEMP(?:ORARY)?\s+)?TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?([\w.\[\]\"`]+)\s*\(", text, re.I):
        name = SR._clean(m.group(1))
        depth, i = 1, m.end()
        while i < len(text) and depth:
            depth += {"(": 1, ")": -1}.get(text[i], 0)
            i += 1
        body = text[m.end():i - 1]
        parts, buf, d = [], "", 0
        for ch in body:
            if ch == "(":
                d += 1
            elif ch == ")":
                d -= 1
            if ch == "," and d == 0:
                parts.append(buf)
                buf = ""
            else:
                buf += ch
        parts.append(buf)
        cols, pks = [], set()
        for p in parts:
            p = " ".join(p.split())
            if not p:
                continue
            up = p.upper()
            mk = re.match(r"(?:CONSTRAINT\s+\S+\s+)?PRIMARY\s+KEY\s*\(([^)]*)\)", p, re.I)
            if mk:
                pks.update(SR._clean(x).lower() for x in mk.group(1).split(","))
                continue
            mf = re.match(r"(?:CONSTRAINT\s+\S+\s+)?FOREIGN\s+KEY\s*\(([^)]*)\)\s*REFERENCES\s+([\w.\[\]\"`]+)", p, re.I)
            if mf:
                for c in cols:
                    if c["name"].lower() == SR._clean(mf.group(1)).lower():
                        c["fk"] = SR._clean(mf.group(2))
                continue
            if re.match(r"(UNIQUE|CHECK|INDEX|KEY|CONSTRAINT)\b", up):
                continue
            mc = re.match(r"([\w\"`\[\]]+)\s+([A-Za-z][\w]*(?:\s*\([^)]*\))?)", p)
            if not mc:
                continue
            col = {"name": SR._clean(mc.group(1)), "type": re.sub(r"\s+", "", mc.group(2)).lower()}
            if "PRIMARY KEY" in up:
                col["pk"] = True
            mr = re.search(r"REFERENCES\s+([\w.\[\]\"`]+)", p, re.I)
            if mr:
                col["fk"] = SR._clean(mr.group(1))
            if "UNIQUE" in up:
                col["unique"] = True
            cols.append(col)
        for c in cols:
            if c["name"].lower() in pks:
                c["pk"] = True
        out.append({"name": name, "columns": cols, "line": SR.line_of(text, m.start())})
    # ALTER TABLE x ADD [CONSTRAINT c] FOREIGN KEY (col) REFERENCES y (col)  (Prisma / migration style)
    by = {t["name"].lower(): t for t in out}
    for m in re.finditer(r"\bALTER\s+TABLE\s+(?:ONLY\s+)?([\w.\[\]\"`]+)\s+ADD\s+(?:CONSTRAINT\s+\S+\s+)?FOREIGN\s+KEY\s*\(([^)]*)\)\s*REFERENCES\s+([\w.\[\]\"`]+)", text, re.I):
        t = by.get(SR._clean(m.group(1)).lower())
        if not t:
            t = {"name": SR._clean(m.group(1)), "columns": [], "line": SR.line_of(text, m.start()), "alter_only": True}
            out.append(t)
            by[t["name"].lower()] = t
        col = SR._clean(m.group(2).split(",")[0])
        c = next((c for c in t["columns"] if c["name"].lower() == col.lower()), None)
        if c is None:
            c = {"name": col, "type": ""}
            t["columns"].append(c)
        c["fk"] = SR._clean(m.group(3))
    return out


def parse_prisma(text):
    """model X { field Type @id @unique @relation(fields: [a], references: [b]) }  ->  same shape as parse_sql_tables."""
    models = {m.group(1) for m in re.finditer(r"^\s*model\s+(\w+)\s*\{", text, re.M)}
    out = []
    for m in re.finditer(r"^\s*model\s+(\w+)\s*\{(.*?)^\s*\}", text, re.M | re.S):
        name, body = m.group(1), m.group(2)
        cols, fks, table = [], {}, name
        for ln in body.split("\n"):
            ln = ln.split("//")[0].strip()
            if not ln:
                continue
            mm = re.match(r'@@map\(\s*"([^"]+)"', ln)
            if mm:
                table = mm.group(1)
                continue
            mm = re.match(r"@@id\(\s*\[([^\]]*)\]", ln)
            if mm:
                for c in cols:
                    if c["name"] in [x.strip() for x in mm.group(1).split(",")]:
                        c["pk"] = True
                continue
            if ln.startswith("@@"):
                continue
            fm = re.match(r"(\w+)\s+([\w]+)(\[\])?(\?)?\s*(.*)$", ln)
            if not fm:
                continue
            fname, ftype, many, _opt, rest = fm.groups()
            rel = re.search(r"@relation\([^)]*fields:\s*\[([^\]]*)\][^)]*references:\s*\[([^\]]*)\]", rest)
            if ftype in models:
                if rel:
                    for f_, r_ in zip(rel.group(1).split(","), rel.group(2).split(",")):
                        fks[f_.strip()] = "%s.%s" % (ftype, r_.strip())
                continue
            c = {"name": fname, "type": ftype.lower() + ("[]" if many else "")}
            if "@id" in rest:
                c["pk"] = True
            if "@unique" in rest:
                c["unique"] = True
            cols.append(c)
        for c in cols:
            if c["name"] in fks:
                c["fk"] = fks[c["name"]]
        out.append({"name": name, "table": table, "columns": cols, "line": SR.line_of(text, m.start()), "prisma": True})
    return out



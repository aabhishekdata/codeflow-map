    def area_map(self):
        """Large code bases: group modules into areas (the folder level below the common prefix)."""
        mods = list(self.A.modules.values())
        if len(mods) <= 24:
            return None
        paths = [M["path"].split("/") for M in mods if M["path"] != "(root)"]
        pre = []
        for parts in zip(*paths):
            if len(set(parts)) != 1:
                break
            pre.append(parts[0])
        area_of = {}
        for M in mods:
            segs = M["path"].split("/") if M["path"] != "(root)" else []
            if not segs:
                area_of[M["id"]] = "(root)"
            elif len(segs) <= len(pre):
                area_of[M["id"]] = "/".join(segs)
            else:
                area_of[M["id"]] = "/".join(segs[:len(pre) + 1])
        n = len(set(area_of.values()))
        if n < 2 or n > 0.8 * len(mods):
            return None
        return area_of


    # ------------------------------------------------------------------ classes facet
    def classes_view(self, M):
        A, s = self.A, self.s(M)
        cls = [c for r in M["files"] for c in A.facts[r].get("classes", []) if r not in A.generated]
        if not cls:
            return None
        key = lambda c: c["file"] + "::" + c["name"]
        mine = {key(c): c for c in cls}
        by_name = defaultdict(list)
        for c in A.cls_index.values():
            by_name[c["name"]].append(c)

        def resolve(name, from_file):
            """Class a name refers to, seen from from_file: imports first, then this module, then a unique repo-wide match."""
            name = (name or "").split(".")[-1].split("<")[0].split("[")[0].strip()
            if not name:
                return None
            tf = A._class_file(from_file, name)
            if tf and A.cls_index.get(tf + "::" + name):
                return A.cls_index[tf + "::" + name]
            here = [c for c in cls if c["name"] == name]
            if here:
                return next((c for c in here if c["file"] == from_file), here[0])
            cands = by_name.get(name, [])
            return cands[0] if len(cands) == 1 else None

        rels, ext = [], {}

        def rel(a, b, t, l):
            if b is None or key(b) == key(a):
                return
            if key(b) not in mine:
                ext[key(b)] = b
            rels.append((key(a), key(b), t, l))
        for c in cls:
            bases = c.get("bases") or ([x.strip() for x in c.get("extends", "").split(",")] if c.get("extends") else [])
            for b in bases:
                rel(c, resolve(b, c["file"]), "inheritance", "")
            for i in c.get("implements", []):
                rel(c, resolve(i, c["file"]), "realization", "")
            for p in c.get("props", []):
                typ = (p.get("type") or "") + " " + " ".join(p.get("decorators", []))
                for w in sorted(set(re.findall(r"[A-Za-z_]\w*", typ))):
                    if w == c["name"] or w in PY_BUILTINS:
                        continue
                    t = resolve(w, c["file"])
                    if t is not None and (key(t) in mine or A.is_table(t)):
                        rel(c, t, "association", p["name"])
                if p.get("fk"):
                    tgt = p["fk"].split(".")[0]
                    hit = next((cc for cc in A.cls_index.values() if A.is_table(cc) and (A.table_name(cc) == tgt or cc["name"] == tgt)), None)
                    if hit is not None:
                        rel(c, hit, "association", p["name"])
        if len(cls) > 30:
            deg = Counter()
            for a, b, _, _ in rels:
                deg[a] += 1
                deg[b] += 1
            cls = sorted(cls, key=lambda c: (-deg[key(c)], -len(c.get("methods", [])) - len(c.get("props", []))))[:30]
            mine = {key(c): c for c in cls}
        shown = set(mine) | set(ext)
        seen, crels = set(), []
        for a, b, t, l in rels:
            if a in shown and b in shown and (a, b, t) not in seen:
                seen.add((a, b, t))
                crels.append({"from": a, "to": b, "type": t, "label": l})
        used_ext = {x for r in crels for x in (r["from"], r["to"])} & set(ext)
        names = Counter(c["name"] for c in list(mine.values()) + [ext[k] for k in used_ext])
        disp = lambda c: c["name"] + (" (%s)" % Path(c["file"]).stem if names[c["name"]] > 1 else "")
        files = sorted({c["file"] for c in mine.values()})
        gid = {r: "fg%d" % i for i, r in enumerate(files)}
        groups = [{"id": gid[r], "label": Path(r).stem, "technical": r} for r in files] if 1 < len(files) <= 8 else []
        classes = []
        for c in mine.values():
            stereo = "table" if A.is_table(c) else "interface" if c.get("interface") else \
                "schema" if any(SCHEMA_BASES.search(b or "") for b in c.get("bases", [])) else ""
            attrs = []
            for p in c.get("props", []):
                typ = p.get("coltype") or p.get("type") or ""
                tag = (" PK" if p.get("pk") else "") + (" FK" if p.get("fk") else "")
                attrs.append(("-" if (p.get("access") == "private" or p["name"].startswith("_")) else "+") + p["name"] + (": " + typ if typ else "") + tag)
            meths = []
            for m in c.get("methods", []):
                prm = ", ".join(x.split(":")[0] for x in m.get("params", []))[:40]
                meths.append(("-" if m.get("access") == "private" else "+") + m["name"] + "(" + prm + ")" + (" " + m["returns"] if m.get("returns") else ""))
            mfns = [A.fns.get(c["file"] + "::" + c["name"] + "." + m["name"]) for m in c.get("methods", [])]
            heat = max([x["heat"] for x in mfns if x] or [0])
            item = {"id": key(c), "key": "c:" + key(c), "label": disp(c), "technical": "%s (%s:%d)" % (c["name"], c["file"], c["line"]),
                    "stereotype": stereo, "attributes": attrs, "methods": meths,
                    "kind": "store" if stereo == "table" else "file" if stereo in ("schema", "interface") else "process",
                    "files": [self.ev(c["file"], c["line"])], "heat": heat, "confidence": "verified",
                    "description": "%s %s in %s with %d field%s and %d method%s." % (
                        {"table": "Database table class", "schema": "Data shape (schema)", "interface": "Type / interface"}.get(stereo, "Class"),
                        c["name"], c["file"], len(attrs), "" if len(attrs) == 1 else "s", len(meths), "" if len(meths) == 1 else "s")}
            if groups:
                item["group"] = gid[c["file"]]
            classes.append(item)
        for k in sorted(used_ext):
            c = ext[k]
            classes.append({"id": k, "label": disp(c), "technical": "%s (%s:%d)" % (c["name"], c["file"], c["line"]), "external": True, "kind": "external",
                            "attributes": [], "methods": [], "files": [self.ev(c["file"], c["line"])],
                            "description": "Defined in another part (%s); shown because classes here build on it or refer to it." % A.modules.get(c["module"], {}).get("label", c["file"])})
        return {"id": "mod-%s-classes" % s, "title": "Classes", "kind": "detail", "module": M["id"], "facet": "classes", "type": "class",
                "groups": groups, "classes": classes, "relations": crels,
                "summary": "The classes and data shapes defined in %s, what they contain and how they relate. Grey boxes live in other parts." % M["label"],
                "technical_summary": "Class diagram: fields, methods, inheritance (hollow triangle), realization and associations from typed fields / foreign keys."}


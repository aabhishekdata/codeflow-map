    # ------------------------------------------------------------------ control flow facet
    def cfg_candidates(self, M):
        A = self.A
        fns = [fn for fn in M["fns"] if fn.get("cfg") and fn["file"] not in A.generated and len(fn["cfg"]["nodes"]) >= 3]
        budget = self.cfg_per_module * (3 if M["id"] in self.select else 1)
        ranked = sorted(fns, key=lambda fn: (-(bool(fn.get("route") or fn.get("entry"))), -fn.get("complexity", 1), -fn.get("loc", 0)))
        pick = [fn for fn in ranked if fn.get("complexity", 1) >= 2 or fn.get("route") or fn.get("entry")][:budget]
        for fn in fns:   # explicitly requested ones
            if fn not in pick and any(self._match_cfg(fn, q) for q in self.cfg_req):
                pick.append(fn)
        return pick

    @staticmethod
    def _match_cfg(fn, q):
        if ":" in q:
            f, name = q.rsplit(":", 1)
            return (fn["file"] == f or fn["file"].endswith("/" + f)) and (fn["qual"] == name or fn["name"] == name)
        return fn["qual"] == q or fn["name"] == q

    def cfg_view(self, M, fn, vid):
        g = fn["cfg"]
        idx = {n["id"]: i for i, n in enumerate(g["nodes"])}
        nodes = []
        for n in g["nodes"]:
            lab = redact(n["label"] or n["t"])
            node = {"id": n["id"], "label": lab, "technical": lab + ("\n· line %d" % n["line"] if n.get("line") else ""),
                    "kind": CFG_KIND.get(n["t"], "process"), "description": CFG_DESC.get(n["t"], ""), "confidence": "verified"}
            if n.get("line"):
                node["files"] = [self.ev(fn["file"], n["line"])]
            nodes.append(node)
        edges = []
        for e in g["edges"]:
            back = g["nodes"][idx[e["to"]]]["t"] == "loop" and idx[e["to"]] < idx[e["from"]]
            edges.append({"from": e["from"], "to": e["to"], "label": e["label"], "style": "dashed" if back else "solid",
                          "description": ("Goes back to the start of the loop for the next round." if back else "")})
        collapsed = g.get("depth", 6) < 6
        return {"id": vid, "title": fn["qual"] + "()", "kind": "detail", "module": M["id"], "facet": "control", "function": fn["key"],
                "type": "flowchart", "direction": "TB", "icons": False, "nodes": nodes, "edges": edges,
                "summary": "Step by step, how %s() decides what to do. Diamonds are decisions with yes/no paths, hexagons are loops, rounded ends are the ways out%s." % (
                    fn["qual"], "; deeply nested parts are summarised in single boxes" if collapsed else ""),
                "technical_summary": "Control-flow graph of %s (%s:%d): cyclomatic complexity %d, %d lines. Dashed arrows return to a loop.%s" % (
                    fn["qual"], fn["file"], fn["line"], fn.get("complexity", 1), fn.get("loc", 0),
                    " Nesting deeper than %d levels is collapsed." % g.get("depth", 6) if collapsed else "")}

    # ------------------------------------------------------------------ sequence facet (draft)
    def seq_candidates(self, M):
        A = self.A
        fns = [fn for fn in M["fns"] if fn["file"] not in A.generated]
        n = 4 if M["id"] in self.select else 2
        out_deg = lambda fn: len({c["to"] for c in fn["resolved"] if c.get("to")}) + len([c for c in fn["resolved"] if c.get("ext")])
        ranked = sorted(fns, key=lambda fn: (-(bool(fn.get("route") or fn.get("entry"))), -out_deg(fn)))
        return [fn for fn in ranked if out_deg(fn) >= 2][:n]

    def seq_view(self, M, fn, vid):
        A = self.A
        parts, steps, seen = {}, [], set()

        def part(key, label, technical, kind, files=None, module=None):
            if key not in parts:
                parts[key] = {"id": "p%d" % len(parts), "label": label, "technical": technical, "kind": kind}
                if files:
                    parts[key]["files"] = files
                if module:
                    parts[key]["description"] = "Code in %s." % module
            return parts[key]["id"]

        def file_part(r):
            return part("f:" + r, human(Path(r).stem), r, self.file_kind(r), [self.ev(r)], A.modules[A.mod_of[r]]["label"] if r in A.mod_of else None)

        if fn.get("route"):
            caller = part("caller", "Caller", "HTTP client", "user")
            steps.append({"from": caller, "to": file_part(fn["file"]), "label": "%s %s" % (fn["route"]["method"], fn["route"]["path"]),
                          "technical": "%s() %s:%d" % (fn["qual"], fn["file"], fn["line"]), "files": [self.ev(fn["file"], fn["line"])]})
        else:
            file_part(fn["file"])

        def visit(key, depth):
            f = A.fns[key]
            seen.add(key)
            for c in f["resolved"]:
                if len(steps) >= 24:
                    return
                src = file_part(f["file"])
                if c.get("to"):
                    g = A.fns[c["to"]]
                    dst = file_part(g["file"])
                    lab = ("creates " + g["cls"]) if self.fn_label(g).startswith("new ") else \
                        ("shows " if c.get("render") else "") + self.fn_label(g)
                    steps.append({"from": src, "to": dst, "label": lab,
                                  "technical": "%s → %s()  %s:%d" % (f["qual"], g["qual"], f["file"], c["line"]),
                                  "files": [self.ev(f["file"], c["line"])]})
                    if depth < 3 and c["to"] not in seen:
                        visit(c["to"], depth + 1)
                elif c.get("ext") == "db":
                    dst = part("db", "Database", "database session / client", "store")
                    steps.append({"from": src, "to": dst, "label": "saves data" if c.get("write") else "reads data",
                                  "technical": "%s.%s()  %s:%d" % (c.get("obj") or "", c["name"], f["file"], c["line"]),
                                  "files": [self.ev(f["file"], c["line"])]})
                elif c.get("ext") == "http":
                    dst = part("http", "Outside service", "HTTP request", "external")
                    steps.append({"from": src, "to": dst, "label": "calls outside service",
                                  "technical": "%s.%s()  %s:%d" % (c.get("obj") or "", c["name"], f["file"], c["line"]),
                                  "files": [self.ev(f["file"], c["line"])]})
        visit(fn["key"], 1)
        merged = []   # back-to-back identical steps become one step with a count
        for st in steps:
            prev = merged[-1] if merged else None
            if prev and prev["from"] == st["from"] and prev["to"] == st["to"] and prev.get("_base", prev["label"]) == st["label"]:
                prev["_n"] = prev.get("_n", 1) + 1
                prev["_base"] = st["label"]
                prev["label"] = "%s (×%d)" % (st["label"], prev["_n"])
                prev["files"] = (prev.get("files") or []) + (st.get("files") or [])
                prev["technical"] = prev["technical"] + "; " + st["technical"].split("  ")[-1]
                continue
            merged.append(dict(st))
        steps = [{k: v for k, v in st.items() if not k.startswith("_")} for st in merged]
        if len(steps) < 2 or len(parts) < 2:
            return None
        if fn.get("route"):
            steps.append({"from": file_part(fn["file"]), "to": parts["caller"]["id"], "label": "sends the response", "reply": True})
        return {"id": vid, "title": self.fn_label(fn) + " (draft)", "kind": "detail", "module": M["id"], "facet": "sequence", "function": fn["key"],
                "type": "sequence", "participants": list(parts.values()), "steps": steps, "draft": True,
                "summary": "Draft, drawn automatically from the calls written in the code, in the order they appear (up to 3 levels deep). It does not show conditions or loops; see Control flow for those.",
                "technical_summary": "Static call trace from %s (%s:%d), depth 3, max 24 steps; participants are files. Conditional and dynamic calls are not distinguished." % (fn["qual"], fn["file"], fn["line"])}


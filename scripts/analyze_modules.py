def find_node(explicit=None):
    exe = explicit or shutil.which("node") or shutil.which("nodejs")
    if not exe:
        return None, None
    try:
        v = subprocess.run([exe, "--version"], capture_output=True, text=True, timeout=20).stdout.strip()
        major = int(re.match(r"v?(\d+)", v).group(1))
    except Exception:
        return None, None
    return (exe, major) if major >= 14 else (None, major)



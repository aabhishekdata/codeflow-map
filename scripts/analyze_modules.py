            dbw = any(c.get("ext") == "db" and c.get("write") for c in fn["resolved"])
            dbr = any(c.get("ext") == "db" and not c.get("write") for c in fn["resolved"]) or any(c["name"] in ("select", "query", "get") for c in fn.get("calls", []))
            touched = [n for n in table_cls if n in names]
            for t in touched:
                tc = table_cls[t]
                sid = node("table:" + t, label=A.table_name(tc), technical="%s (%s)" % (t, tc["file"]), kind="store", group="data",
                           description="Database table defined by %s in %s." % (t, tc["file"]), files=[self.ev(tc["file"], tc["line"])])
                if dbw:
                    file_has[r]["out"].add((sid, "saves", t in sens_tables))
                if dbr or not dbw:
                    file_has[r]["in"].add((sid, "reads", t in sens_tables))
            for c in fn["resolved"]:
                if c.get("ext") == "http":
                    xid = node("http", label="Outside service", technical="HTTP calls", kind="external", group="out", description="Network calls to services outside this code.")

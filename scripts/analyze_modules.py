        used = {g for g in (n.get("group") for n in nodes) if g}
        groups = [g for g in [{"id": "in", "label": "Comes in"}, {"id": "work", "label": "Handled by"}, {"id": "data", "label": "Data stores"},
                              {"id": "out", "label": "Goes out"}] if g["id"] in used]
